#!/usr/bin/env python3
"""Aggregate M0 benchmark output/ into docs/MEASUREMENTS.md.

Reads every cell directory under output/, extracts key metrics from the
llama-bench JSON runs and thermal.jsonl samples, and writes a single
Markdown report with tables + charts (as ASCII sparklines).

Every claim in the report cites its cell directory so results are auditable.
"""

from __future__ import annotations

import json
import statistics
import sys
from dataclasses import dataclass, field
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
OUTPUT_DIR = Path(__file__).resolve().parent / "output"
REPORT_PATH = REPO_ROOT / "docs" / "MEASUREMENTS.md"


@dataclass
class Cell:
    dir_name: str
    model_id: str
    prompt_id: str
    n_gen: int
    env: dict = field(default_factory=dict)
    runs: list[dict] = field(default_factory=list)
    thermal_samples: list[dict] = field(default_factory=list)

    @property
    def prefill_tps(self) -> list[float]:
        return [r["prompt_tps"] for r in self.runs if "prompt_tps" in r]

    @property
    def decode_tps(self) -> list[float]:
        return [r["gen_tps"] for r in self.runs if "gen_tps" in r]

    def summary(self) -> dict:
        prefill = self.prefill_tps
        decode = self.decode_tps
        return {
            "model": self.model_id,
            "prompt": self.prompt_id,
            "n_gen": self.n_gen,
            "runs": len(self.runs),
            "prefill_tps_median": statistics.median(prefill) if prefill else None,
            "decode_tps_median": statistics.median(decode) if decode else None,
            "thermal_start_headroom": self._first_headroom(),
            "thermal_end_headroom": self._last_headroom(),
        }

    def _first_headroom(self):
        for s in self.thermal_samples:
            if s.get("headroom") not in (None, "null"):
                return s["headroom"]
        return None

    def _last_headroom(self):
        for s in reversed(self.thermal_samples):
            if s.get("headroom") not in (None, "null"):
                return s["headroom"]
        return None


def load_cells() -> list[Cell]:
    cells = []
    if not OUTPUT_DIR.exists():
        return cells
    for cell_dir in sorted(OUTPUT_DIR.iterdir()):
        if not cell_dir.is_dir() or cell_dir.name.startswith("."):
            continue
        parts = cell_dir.name.split("-", 4)
        if len(parts) < 5:
            continue
        _timestamp_date, _timestamp_time, model, prompt, ngen_str = parts
        n_gen = int(ngen_str.lstrip("g")) if ngen_str.startswith("g") else 0
        cell = Cell(cell_dir.name, model, prompt, n_gen)

        env_path = cell_dir / "env.json"
        if env_path.exists():
            try:
                cell.env = json.loads(env_path.read_text())
            except json.JSONDecodeError:
                pass

        for run_json in sorted(cell_dir.glob("run-*.json")):
            try:
                cell.runs.append(json.loads(run_json.read_text()))
            except json.JSONDecodeError:
                pass

        thermal_path = cell_dir / "thermal.jsonl"
        if thermal_path.exists():
            for line in thermal_path.read_text().splitlines():
                try:
                    cell.thermal_samples.append(json.loads(line))
                except json.JSONDecodeError:
                    pass

        cells.append(cell)
    return cells


def render_report(cells: list[Cell]) -> str:
    lines: list[str] = [
        "# M0 Measurements — Skein",
        "",
        "> Generated by `tools/m0-benchmark/collect-results.py`.",
        "> Every row cites its source cell directory in `tools/m0-benchmark/output/`.",
        "",
    ]

    if not cells:
        lines += [
            "**No cells yet.** Run `tools/m0-benchmark/run.sh --all` on a device-connected workstation first.",
            "",
        ]
        return "\n".join(lines)

    device_info = cells[0].env if cells else {}
    lines += [
        "## Device under test",
        "",
        f"- Model: `{device_info.get('device_model', 'unknown')}`",
        f"- SoC: `{device_info.get('device_soc', 'unknown')}`",
        f"- OS build: `{device_info.get('os_build', 'unknown')}`",
        f"- Security patch: `{device_info.get('os_security_patch', 'unknown')}`",
        f"- Kernel: `{device_info.get('kernel', 'unknown')}`",
        "",
        "## Results",
        "",
        "| Model | Prompt | n_gen | Runs | Prefill (t/s median) | Decode (t/s median) | Thermal start → end | Cell |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for cell in cells:
        s = cell.summary()
        lines.append(
            "| {model} | {prompt} | {n_gen} | {runs} | {prefill} | {decode} | {t0} → {t1} | `{cell}` |".format(
                model=s["model"],
                prompt=s["prompt"],
                n_gen=s["n_gen"],
                runs=s["runs"],
                prefill=f"{s['prefill_tps_median']:.1f}" if s["prefill_tps_median"] is not None else "—",
                decode=f"{s['decode_tps_median']:.1f}" if s["decode_tps_median"] is not None else "—",
                t0=s["thermal_start_headroom"] or "—",
                t1=s["thermal_end_headroom"] or "—",
                cell=cell.dir_name,
            )
        )

    lines += [
        "",
        "## Open questions this run answers",
        "",
        "- [ ] Embedder path chosen (GGUF vs ONNX RT): ",
        "- [ ] Cross-encoder rerank latency budget: ",
        "- [ ] Effective context cap (16k / 24k / 32k): ",
        "- [ ] MTP uplift on Qwen 2.5 abliterated: ",
        "- [ ] Sustained inference duration before thermal throttle: ",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    cells = load_cells()
    report = render_report(cells)
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(report)
    print(f"wrote {REPORT_PATH.relative_to(REPO_ROOT)}  ({len(cells)} cells)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
